const int FONT_SIZE = sizeof(FONT) / sizeof(FONT[0]);

// Find the glyph for one character, or nullptr (draw nothing) if unknown.
const Glyph* findGlyph(char c) {
    if (c >= 'a' && c <= 'z') c = c - 'a' + 'A';   // lower case -> upper case
    for (int i = 0; i < FONT_SIZE; i++) {
        if (FONT[i].symbol == c) return &FONT[i];
    }
    return nullptr;
}

