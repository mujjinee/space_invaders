void drawBox(sf::RenderTarget& window, float x, float y,
             float width, float height, sf::Color color) {
    sf::RectangleShape box({width, height});
    box.setPosition({x, y});
    box.setFillColor(color);
    window.draw(box);
}

void drawText(sf::RenderTarget& window, const std::string& text,
              float x, float y, float scale, sf::Color color) {
    for (char c : text) {
        const Glyph* glyph = findGlyph(c);
        if (glyph != nullptr) {
            for (int row = 0; row < 7; row++) {
                for (int col = 0; col < 5; col++) {
                    if (glyph->rows[row][col] == '1') {
                        drawBox(window, x + col * scale, y + row * scale, scale, scale, color);
                    }
                }
            }
        }
        x += 6.0f * scale;   // 5 pixels for the letter + 1 pixel of space
    }
}

float textWidth(const std::string& text, float scale) {
    if (text.empty()) return 0.0f;
    return (6.0f * text.size() - 1.0f) * scale;
}
